"""Capture screenshots of the online data portals used by the workshop.

Saves PNGs into ``docs/workshop/images/`` that are embedded by
``docs/workshop/2.data.ipynb`` (generated by ``generate_workshop_series.py``).

Run from the repo root:

    .venv/bin/python scripts/capture_portal_screenshots.py [--out docs/workshop/images]

Requires Playwright + Chromium:
    pip install playwright && playwright install chromium

The script is defensive: a portal that times out or blocks headless rendering
is reported and skipped rather than aborting the whole run.
"""

